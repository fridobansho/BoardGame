        private static readonly HashSet<string> _words = BuildDictionary();
        private static readonly List<string>[] _wordsByLetter = BuildLetterIndex(_words);

        public static IReadOnlyCollection<string> Words => _words;

        public static bool IsValidWord(string word)
        {
            if (string.IsNullOrWhiteSpace(word) || word.Length < 2)
            {
                return false;
            }
            return _words.Contains(word.Trim().ToUpperInvariant());
        }

        public static IReadOnlyList<string> GetWordsContaining(char letter)
        {
            char upper = char.ToUpperInvariant(letter);
            if (upper < 'A' || upper > 'Z') return Array.Empty<string>();
            return _wordsByLetter[upper - 'A'];
        }

        public static void AddWord(string word)
        {
            if (string.IsNullOrWhiteSpace(word)) return;
            string upper = word.Trim().ToUpperInvariant();
            if (upper.Length < 2) return;
            foreach (char c in upper)
            {
                if (c < 'A' || c > 'Z') return;
            }

            if (_words.Add(upper))
            {
                var seen = new HashSet<char>();
                foreach (char c in upper)
                {
                    if (seen.Add(c))
                    {
                        _wordsByLetter[c - 'A'].Add(upper);
                    }
                }
            }
        }

        private static List<string>[] BuildLetterIndex(HashSet<string> words)
        {
            var index = new List<string>[26];
            for (int i = 0; i < 26; i++) index[i] = new List<string>();

            foreach (var word in words)
            {
                var seen = new HashSet<char>();
                foreach (char c in word)
                {
                    if (c >= 'A' && c <= 'Z' && seen.Add(c))
                    {
                        index[c - 'A'].Add(word);
                    }
                }
            }
            return index;
        }

